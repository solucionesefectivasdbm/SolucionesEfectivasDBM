FECHA = date(2026, 3, 1)  # fecha_pago_real of every forward registration


@pytest_asyncio.fixture
async def db(test_engine) -> AsyncGenerator[AsyncSession, None]:
    """Session like production (autoflush=False): the service must not rely on implicit flushes."""
    maker = async_sessionmaker(
        bind=test_engine, class_=AsyncSession, expire_on_commit=False, autoflush=False,
    )
    async with maker() as session:
        yield session
        await session.rollback()


async def _credito(
    db, tipo=TipoCredito.cuota_fija, capital="1000000.00", cuotas=10, abono_minimo=None,
) -> tuple[Credito, Pago]:
    """Monthly 3% credit plus its first cuota, validated and assigned to a bank account.
    Cliente / cuenta rows are not created: SQLite does not enforce those FKs."""
    cuota_fija = tipo == TipoCredito.cuota_fija
    capital = Decimal(capital)
    credito = Credito(
        id=uuid.uuid4(), cliente_id=uuid.uuid4(), numero_credito_cliente=f"RM-{uuid.uuid4().hex[:10]}",
        tipo_credito=tipo, capital_prestado=capital, tasa_interes_mensual=Decimal("0.0300"),
        fecha_apertura=date(2026, 1, 1), fecha_inicial_pago=date(2026, 2, 1),
        periodicidad=Periodicidad.mensual, saldo_capital=capital, abono_minimo=abono_minimo,
        saldo_intereses=(
            (capital * Decimal("0.03") * cuotas).quantize(Decimal("0.01")) if cuota_fija else Decimal("0.00")
        ),
        numero_cuotas=cuotas if cuota_fija else None, activo=True,
    )
    db.add(credito)
    await db.flush()
    primera = await crear_primera_cuota(credito, uuid.uuid4())
    primera.validado_recaudador, primera.tipo_validacion = True, "completo"
    db.add(primera)
    await db.flush()
    return credito, primera


async def _registrar(db, credito, pago, capital, interes, destino=None) -> None:
    """Forward registration through the real services (exact / partial, or excedente), flushed like a commit."""
    montos = RegistrarPagoRequest(capital_pagado=Decimal(capital), interes_pagado=Decimal(interes))
    if destino:
        await PagoService.confirmar_excedente(db, pago, credito, montos, destino, FECHA)
    else:
        await PagoService.registrar_pago(db, pago, credito, montos, FECHA)
    await db.flush()


async def _pagos(db, credito) -> list[Pago]:
    """Every pago of the credit (soft-deleted included), as the router will hand them over."""
    rows = await db.execute(
        select(Pago).where(Pago.credito_id == credito.id).order_by(Pago.numero_cuota, Pago.id)
    )
    return list(rows.scalars())


async def _pendientes(db, credito) -> list[Pago]:
    """Unpaid, not-deleted cuotas of the credit, in order."""
    return [p for p in await _pagos(db, credito) if not p.pagado and p.deleted_at is None]


async def _repartos_borrados(db, pago_id) -> list[bool]:
    """One flag per reparto row of the pago (True = soft-deleted), read straight from the DB."""
    rows = await db.execute(
        select(PagoReparto.deleted_at).where(PagoReparto.pago_id == pago_id).order_by(PagoReparto.id)
    )
    return [borrado is not None for borrado in rows.scalars()]


async def _revertir(db, credito, pago):
    resultado = await PagoService.revertir_monto(db, pago, credito, await _pagos(db, credito))
    await db.flush()  # what the router's commit does: the changes must be persistable
    return resultado


def _cambios(resultado) -> dict:
    """ResultadoReversion.cambios keyed by (entidad, entidad_id)."""
    return {(c.entidad, c.entidad_id): c for c in resultado.cambios}


@pytest_asyncio.fixture
async def registrado(db) -> tuple[Credito, Pago, Pago]:
    """cuota_fija 1,000,000 / 10: cuota #1 (100000 + 30000) paid exactly -> balances 900000 / 270000.
    Returns (credito, cuota #1, cuota #2 generated by that registration)."""
    credito, pago = await _credito(db)
    await _registrar(db, credito, pago, "100000.00", "30000.00")
    return credito, pago, (await _pendientes(db, credito))[0]


def _cuota(numero, tipo=TipoCuota.programada, pagado=False, borrada=False) -> Pago:
    return Pago(
        id=uuid.uuid4(), numero_cuota=numero, tipo_cuota=tipo, pagado=pagado,
        deleted_at=datetime(2026, 3, 2) if borrada else None,
    )


class TestCuotasSucesoras:
    def test_son_las_programadas_pendientes_vigentes_y_posteriores(self):
        previa, revertida, sucesora = _cuota(1, pagado=True), _cuota(2, pagado=True), _cuota(3)
        no_programado = _cuota(0, tipo=TipoCuota.no_programada, pagado=True)
        pagos = [
            no_programado, previa, revertida, sucesora,
            _cuota(4, borrada=True),                  # already soft-deleted
            _cuota(5, tipo=TipoCuota.no_programada),  # never part of the schedule chain
            _cuota(6, pagado=True),                   # paid later cuota: a LIFO matter, not a successor
        ]
        assert PagoService.cuotas_sucesoras(revertida, pagos) == [sucesora]
        assert PagoService.cuotas_sucesoras(no_programado, pagos) == []  # a no_programada generates none


@pytest.mark.asyncio
class TestCuotaProgramada:
    """cuota_fija, open credit: cuota #1 paid exactly, then reverted."""

    async def test_restaura_la_cuota_a_validada_sin_pagar_conservando_sus_montos_esperados(self, db, registrado):
        """D5: a recompute would reset the tampered amounts to 100000 / 30000 / 130000 / False."""
        credito, pago, _ = registrado
        pago.interes_a_pagar, pago.monto_a_pagar, pago.es_ultimo_pago = Decimal("31234.00"), Decimal("131234.00"), True
        await _revertir(db, credito, pago)

        assert (pago.pagado, pago.capital_pagado, pago.interes_pagado) == (False, Decimal("0.00"), Decimal("0.00"))
        assert (pago.fecha_pago_real, pago.es_excedente_a, pago.deleted_at) == (None, None, None)
        assert (pago.validado_recaudador, pago.tipo_validacion) == (True, "completo")
        assert (pago.capital_a_pagar, pago.interes_a_pagar, pago.monto_a_pagar, pago.es_ultimo_pago) == (
            Decimal("100000.00"), Decimal("31234.00"), Decimal("131234.00"), True,
        )

    async def test_borra_la_cuota_sucesora_y_los_repartos_del_pago(self, db, registrado):
        credito, pago, sucesora = registrado
        assert (sucesora.numero_cuota, sucesora.deleted_at) == (2, None)
        assert await _repartos_borrados(db, pago.id) == [False]
        await _revertir(db, credito, pago)

        assert sucesora.deleted_at is not None
        assert [p.id for p in await _pendientes(db, credito)] == [pago.id]
        assert await _repartos_borrados(db, pago.id) == [True]

    async def test_recompone_los_saldos_previos_y_mantiene_el_credito_abierto(self, db, registrado):
        credito, pago, _ = registrado
        assert (credito.saldo_capital, credito.saldo_intereses) == (Decimal("900000.00"), Decimal("270000.00"))
        await _revertir(db, credito, pago)

        assert (credito.saldo_capital, credito.saldo_intereses, credito.activo) == (
            Decimal("1000000.00"), Decimal("300000.00"), True,
        )

    async def test_lista_los_cambios_para_la_auditoria(self, db, registrado):
        credito, pago, sucesora = registrado
        cambios = _cambios(await _revertir(db, credito, pago))

        assert set(cambios) == {("pagos", pago.id), ("pagos", sucesora.id), ("creditos", credito.id)}
        assert cambios[("pagos", pago.id)].campos == {
            "pagado": ("True", "False"), "capital_pagado": ("100000.00", "0.00"),
            "interes_pagado": ("30000.00", "0.00"), "fecha_pago_real": ("2026-03-01", "None"),
        }
        assert cambios[("pagos", pago.id)].eliminado is False
        assert cambios[("pagos", sucesora.id)].eliminado is True
        # No `activo`: the credit was open and stays open.
        assert cambios[("creditos", credito.id)].campos == {
            "saldo_capital": ("900000.00", "1000000.00"), "saldo_intereses": ("270000.00", "300000.00"),
        }


@pytest.mark.asyncio
class TestExcedente:
    """Destino is authoritative: the reverted balances must not depend on the reported split."""

    @pytest.mark.parametrize(
        "destino, capital, interes, saldos",
        [
            pytest.param(DestinoExcedente.capital, "100000.00", "50000.00", ("880000.00", "270000.00"), id="a-capital"),
            pytest.param(DestinoExcedente.intereses, "120000.00", "30000.00", ("900000.00", "250000.00"), id="a-intereses"),
        ],
    )
    async def test_devuelve_los_saldos_previos_y_limpia_el_destino(self, db, destino, capital, interes, saldos):
        credito, pago = await _credito(db)
        await _registrar(db, credito, pago, capital, interes, destino)
        assert (credito.saldo_capital, credito.saldo_intereses) == tuple(Decimal(s) for s in saldos)
        assert pago.es_excedente_a == destino

        cambios = _cambios(await _revertir(db, credito, pago))

        assert (credito.saldo_capital, credito.saldo_intereses) == (Decimal("1000000.00"), Decimal("300000.00"))
        assert pago.es_excedente_a is None
        assert cambios[("pagos", pago.id)].campos["es_excedente_a"] == (destino.value, "None")


@pytest.mark.asyncio
class TestCreditoCerrado:
    async def test_reabre_el_credito_saldado_ignorando_los_pagos_eliminados(self, db):
        credito, pago = await _credito(db, capital="100000.00", cuotas=1)
        await _registrar(db, credito, pago, "100000.00", "3000.00")
        assert (credito.activo, credito.saldo_capital, credito.saldo_intereses) == (False, Decimal("0.00"), Decimal("0.00"))
        # An earlier reverted no_programada keeps its amounts (D6) but must not feed the interest replay.
        db.add(Pago(
            credito_id=credito.id, numero_cuota=2, tipo_cuota=TipoCuota.no_programada,
            monto_a_pagar=Decimal("40000.00"), interes_pagado=Decimal("40000.00"), momento="m3",
            fecha_maxima=FECHA, pagado=True, deleted_at=datetime(2026, 3, 2),
        ))
        await db.flush()

        resultado = await _revertir(db, credito, pago)

        assert (credito.activo, credito.saldo_capital, credito.saldo_intereses) == (
            True, Decimal("100000.00"), Decimal("3000.00"),
        )
        assert [p.id for p in await _pendientes(db, credito)] == [pago.id]  # settled: no successor to delete
        assert _cambios(resultado)[("creditos", credito.id)].campos == {
            "saldo_capital": ("0.00", "100000.00"), "saldo_intereses": ("0.00", "3000.00"),
            "activo": ("False", "True"),
        }

    async def test_cierre_con_interes_pendiente_reabre_con_el_interes_del_cronograma(self, db):
        """Regla 14 zeroed saldo_intereses at closure: D3 rebuilds it from the schedule (3000), not 0."""
        credito, p1 = await _credito(db, capital="100000.00", cuotas=2)  # 50000 + 3000 per cuota
        await _registrar(db, credito, p1, "50000.00", "3000.00")
        p2 = (await _pendientes(db, credito))[0]
        await _registrar(db, credito, p2, "50000.00", "0.00")  # partial: capital settled, 3000 interest pending
        cerrar_credito_con_interes_pendiente(credito)
        await db.flush()
        cola = (await _pendientes(db, credito))[0]
        assert (cola.numero_cuota, cola.tipo_cuota, cola.interes_a_pagar) == (3, TipoCuota.interes, Decimal("3000.00"))
        assert (credito.activo, credito.saldo_capital, credito.saldo_intereses) == (False, Decimal("0.00"), Decimal("0.00"))

        await _revertir(db, credito, p2)

        assert (credito.activo, credito.saldo_capital, credito.saldo_intereses) == (
            True, Decimal("50000.00"), Decimal("3000.00"),
        )
        assert cola.deleted_at is not None
        assert [p.id for p in await _pendientes(db, credito)] == [p2.id]


@pytest.mark.asyncio
class TestPagoNoProgramado:
    async def test_borra_el_pago_y_sus_repartos_y_recalcula_la_cuota_actual(self, db):
        """D6: a no_programada payment was never validated, so it is soft-deleted (not restored)."""
        credito, cuota = await _credito(db, tipo=TipoCredito.abono_capital, abono_minimo=Decimal("50000.00"))
        pago = await PagoService.registrar_pago_no_programado(
            db, credito, Decimal("200000.00"), DestinoExcedente.capital, FECHA, cuota.cuenta_bancaria_id,
        )
        await db.flush()
        # Forward state: the interest of the current cuota was recomputed on the lower balance.
        assert (credito.saldo_capital, cuota.interes_a_pagar, cuota.monto_a_pagar) == (
            Decimal("800000.00"), Decimal("24000.00"), Decimal("74000.00"),
        )
        assert await _repartos_borrados(db, pago.id) == [False]

        resultado = await _revertir(db, credito, pago)

        assert pago.deleted_at is not None
        assert await _repartos_borrados(db, pago.id) == [True]
        assert (credito.saldo_capital, credito.saldo_intereses, credito.activo) == (
            Decimal("1000000.00"), Decimal("0.00"), True,
        )
        assert (cuota.interes_a_pagar, cuota.monto_a_pagar) == (Decimal("30000.00"), Decimal("80000.00"))
        assert [p.id for p in await _pendientes(db, credito)] == [cuota.id]  # nothing left in its place
        assert _cambios(resultado)[("pagos", pago.id)].eliminado is True
